import { projectToSvg } from "./country-centroids";

/**
 * Simplified world coastlines for the shipment-lane map, expressed as
 * [latitude, longitude] chains (approximate, hand-placed from general
 * geography) and projected into the SVG viewBox with the same projection
 * used for the country markers — so land shapes and markers always align.
 *
 * Inland seas that would otherwise be swallowed by the outlines (Black Sea,
 * Caspian) are drawn back on top as SEA_PATCHES in the panel background
 * color.
 */

export const MAP_W = 1000;
export const MAP_H = 500;

type LatLng = [number, number];

function toPath(points: LatLng[]): string {
  return (
    points
      .map(([lat, lng], i) => {
        const { x, y } = projectToSvg(lat, lng, MAP_W, MAP_H);
        return `${i === 0 ? "M" : "L"}${x.toFixed(1)},${y.toFixed(1)}`;
      })
      .join(" ") + " Z"
  );
}

